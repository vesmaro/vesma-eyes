def build_source_pages(
    name: str,
    source: dict[str, Any],
    pin: dict[str, Any],
    corpus_slugs: set[str],
    normalize: dict[str, Any],
) -> tuple[list[dict[str, Any]], dict[str, Any]]:
    """Included md files from one pinned clone, sync_docs L1 rules applied."""
    repo = Path(pin["repo_path"])
    locale_dirs: dict[str, str] = source.get("locale_dirs") or {"en": "docs"}
    web_base = source.get("web_base", "")
    stats: dict[str, list[Any]] = {
        "included_slugs": sorted(corpus_slugs),
        "asset_copies": [],
        "images": [],
        "dangling_slugs": [],
        "github_links": [],
        "escapes": [],
        "missing_targets": [],
        "overlays_applied": [],
    }
    pages: list[dict[str, Any]] = []
    report: dict[str, Any] = {"skipped": []}

    for entry in source["include"]:
        for locale, locale_dir in sorted(locale_dirs.items()):
            object_path = f"{pin['sha']}:{locale_dir}/{entry['path']}"
            try:
                raw = run_git(repo, "show", object_path)
            except SyncError:
                report["skipped"].append(f"{locale}/{entry['path']}: missing at pin {pin['sha'][:12]}")
                continue
            body = strip_chrome(raw, normalize)
            body = normalize_mermaid_labels(body)
            rewriter = sync_docs.Rewriter(
                project=name,
                repo=repo,
                sha=pin["sha"],
                web_base=web_base,
                locale_dirs=locale_dirs,
                source_dir="/".join(posix_dir(locale_dir, entry["path"])),
                assets_out=sync_docs.ASSETS_UPSTREAM,
                stats=stats,
            )
            body = rewriter.rewrite(body)
            title = entry.get("title") or {}
            if isinstance(title, dict):
                title = title.get(locale) or first_h1(body) or entry["path"]
            note = entry.get("note") or {}
            if isinstance(note, dict):
                note = note.get(locale)
            slug_tail = entry["slug"].strip("/")
            pages.append(
                {
                    "path": f"{slug_tail}.md",
                    "locale": locale,
                    "title": str(title),
                    "category": str(entry["category"]),
                    "order": int(entry["order"]),
                    "body": body,
                    "banner": GEN_BANNER_TEMPLATE.format(source=name, sha12=pin["sha"][:12]),
                    "extra_fields": [("source", f"{name}@{pin['sha'][:12]}")],
                    "note": str(note).strip() if note else None,
                    "provenance": {
                        "repo": name,
                        "source_path": f"{locale_dir}/{entry['path']}",
                        "sha": pin["sha"],
                        "commit_date": pin["commit_date"],
                    },
                    "kind": "upstream",
                }
            )
    report["dangling_slugs"] = sorted(set(stats["dangling_slugs"]))
    report["github_links"] = sorted(set(stats["github_links"]))
    report["escapes"] = sorted(set(stats["escapes"]))
    report["missing_targets"] = sorted(set(stats["missing_targets"]))
    return pages, report


def posix_dir(*parts: str) -> list[str]:
    import posixpath

    directory = posixpath.dirname("/".join(parts))
    return directory.split("/") if directory else []


# --------------------------------------------------------------------------
# curated pages (our layer, outside the wiped zone)
# --------------------------------------------------------------------------

def build_curated_pages(
    curated: list[dict[str, Any]], pins: dict[str, dict[str, Any]]
) -> tuple[list[dict[str, Any]], list[str]]:
    pages: list[dict[str, Any]] = []
    warnings: list[str] = []
    for entry in curated:
        slug_tail = entry["slug"].strip("/")
        published: dict[str, dict[str, Any]] = {}
        for locale in ("ru", "en"):
            curated_file = CURATED_DIR / locale / f"{slug_tail}.md"
            if not curated_file.is_file():
                warnings.append(f"curated file missing: {curated_file} (locale skipped)")
                continue
            meta, body = split_frontmatter(
                curated_file.read_text(encoding="utf-8"), str(curated_file)
            )
            body = normalize_mermaid_labels(body)
            title = meta.get("title") or first_h1(body) or slug_tail
            published[locale] = {
                "path": f"{slug_tail}.md",
                "locale": locale,
                "title": title,
                "category": str(entry["category"]),
                "order": int(entry["order"]),
                "body": body,
                "banner": CURATED_BANNER_TEMPLATE.format(
                    source=f"curated/api/{locale}/{slug_tail}.md"
                ),
                "extra_fields": [],
                "provenance": curated_provenance(entry, pins),
                "kind": "curated",
            }
        if not published:
            warnings.append(f"curated page {slug_tail}: no locales published")
            continue
        pages.extend(published[locale] for locale in sorted(published))
    return pages, warnings


def curated_provenance(entry: dict[str, Any], pins: dict[str, dict[str, Any]]) -> dict[str, str]:
    """Curated pages carry the pin of the source they were verified against."""
    verify = entry.get("verified_against") or {}
    pin = pins.get(verify.get("source", ""))
    if pin and verify.get("sha") == "pin":
        return {
            "repo": verify["source"],
            "source_path": str(verify.get("path", "")),
            "sha": pin["sha"],
            "commit_date": pin["commit_date"],
        }
    # Hub-internal curation: pin our own HEAD (honest "verified at").
    head = run_git(REPO_ROOT, "rev-parse", "HEAD")
    return {
        "repo": "vesmaro-eyes",
        "source_path": str(verify.get("path", "docs")),
        "sha": head,
        "commit_date": run_git(REPO_ROOT, "log", "-1", "--format=%cI"),
    }


