def load_api_hub_config(path: Path) -> tuple[dict[str, Any], dict[str, Any]]:
    """(full config, api_hub section) — the GLOBAL `normalize` rules apply
    to api-hub upstream bodies exactly like to the sync corpus."""
    config = yaml.safe_load(path.read_text(encoding="utf-8"))
    if not isinstance(config, dict):
        raise SyncError(f"{path}: expected a yaml mapping")
    hub = config.get("api_hub")
    if not isinstance(hub, dict):
        raise SyncError(f"{path}: no `api_hub:` section — the api hub owns it")
    for key in ("url_prefix", "sources", "board_api", "curated"):
        if key not in hub:
            raise SyncError(f"{path}: api_hub lacks `{key}`")
    if hub["url_prefix"] != "api":
        raise SyncError(
            f"{path}: api_hub.url_prefix must stay `api` "
            f"(projects.ts registry owns the segment)"
        )
    for name, source in hub["sources"].items():
        for key in ("repo", "ref", "include"):
            if key not in source:
                raise SyncError(f"{path}: api_hub.sources.{name} lacks `{key}`")
    return config, hub


