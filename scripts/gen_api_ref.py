def sync(config: dict[str, Any], hub: dict[str, Any]) -> dict[str, Any]:
    normalize = sync_docs.normalize_rules(config)
    pins: dict[str, dict[str, Any]] = {}
    for name, source in hub["sources"].items():
        pins[name] = pin_source(name, source)
    pins["__spec__"] = spec_provenance(REPO_ROOT / hub["board_api"]["spec"])

    sidecar_slugs: set[str] = set()
    sidecar_path = CONTENT_UPSTREAM / SIDECAR_NAME
    if sidecar_path.is_file():
        existing = json.loads(sidecar_path.read_text(encoding="utf-8"))
        sidecar_slugs = {entry["slug"] for entry in existing.get("pages", [])}

    report: dict[str, Any] = {"sources": {}, "skipped": [], "warnings": []}

    board_pages, total_ops = build_board_pages(hub["board_api"], pins["__spec__"])
    report["board_api"] = {
        "pages": len(board_pages),
        "pages_per_locale": len(board_pages) // len(BOARD_LOCALES),
        "locales": list(BOARD_LOCALES),
        "operations": total_ops,
        "spec_blob": pins["__spec__"]["sha"][:12],
        "spec_version": json.loads((REPO_ROOT / hub["board_api"]["spec"]).read_text(encoding="utf-8"))["info"]["version"],
    }

    own_slugs = {
        f"{hub['url_prefix']}/{page['path'][: -len('.md')]}" for page in board_pages
    }
    corpus_slugs = sidecar_slugs | own_slugs

    pages = list(board_pages)
    for name, source in sorted(hub["sources"].items()):
        source_pages, source_report = build_source_pages(
            name, source, pins[name], corpus_slugs, normalize
        )
        pages.extend(source_pages)
        corpus_slugs |= {
            f"{hub['url_prefix']}/{page['path'][: -len('.md')]}" for page in source_pages
        }
        report["sources"][name] = {
            "sha": pins[name]["sha"],
            "pages": len(source_pages),
            **source_report,
        }

    curated_pages, warnings = build_curated_pages(hub["curated"], pins)
    pages.extend(curated_pages)
    report["warnings"].extend(warnings)

    # --- phase B: wipe the api subtree, write everything --------------------
    if API_DIR.exists():
        shutil.rmtree(API_DIR)
    for page in pages:
        dest, md = page_to_file(page, hub["url_prefix"])
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(md, encoding="utf-8")

    merged = merge_manifests(pages, hub["url_prefix"], hub, pins)

    # --- reuse the sync_docs contentClass gate over the FULL merged tree ----
    provenance = json.loads((CONTENT_UPSTREAM / PROVENANCE_NAME).read_text(encoding="utf-8"))
    sidecar = json.loads((CONTENT_UPSTREAM / SIDECAR_NAME).read_text(encoding="utf-8"))
    sidecar_by_slug = {entry["slug"]: entry for entry in sidecar["pages"]}
    sync_docs._verify_content_class_gate(sidecar_by_slug, provenance["files"], CONTENT_UPSTREAM)

    report.update(
        {
            "pages": merged["pages"],
            "provenance_files": merged["files"],
            "pins": {
                key: pin["sha"] if key != "__spec__" else pin["sha"]
                for key, pin in pins.items()
            },
        }
    )
    return report


