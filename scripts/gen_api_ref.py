def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "command", nargs="?", choices=("sync", "check-drift"), default="sync",
        help="sync (default) regenerates the api corpus; check-drift is report-only",
    )
    parser.add_argument("--config", type=Path, default=DEFAULT_CONFIG)
    args = parser.parse_args(argv)

    try:
        config, hub = load_api_hub_config(args.config)
        if args.command == "check-drift":
            check_drift(hub)
            return 0
        report = sync(config, hub)
    except SyncError as error:
        print(f"gen_api_ref: {error}", file=sys.stderr)
        return 1
    board = report["board_api"]
    print(
        f"[api/board] spec blob {board['spec_blob']} v{board['spec_version']}: "
        f"{board['operations']} операций → {board['pages']} страниц"
    )
    for name, info in report["sources"].items():
        print(
            f"[api/{name}] pinned {info['sha'][:12]}: {info['pages']} страниц; "
            f"github-ссылок {len(info.get('github_links', []))}, "
            f"dangling {info.get('dangling_slugs', [])}"
        )
        for skip in info.get("skipped", []):
            print(f"  [skip] {skip}")
    for warning in report["warnings"]:
        print(f"[warn] {warning}")
    print(
        f"total: {report['pages']} api-страниц в сайдкаре "
        f"({report['provenance_files']} записей provenance); "
        f"contentClass gate пройден"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
