def check_drift(hub: dict[str, Any]) -> None:
    """Report-only. NOTE: api-hub bodies are read from git OBJECTS of the
    pin (see pin_source), so a differing clone HEAD is INFORMATIONAL — the
    ../mnemos and ../mnemos-mesh clones are SHARED with the sync_docs
    projects, whose pins legitimately own the checkout state."""
    for name, source in sorted(hub["sources"].items()):
        repo = (REPO_ROOT / source["repo"]).resolve()
        pinned = resolve_sha(repo, source["ref"])
        head = resolve_sha(repo, "HEAD")
        same = "OK" if head == pinned else "checkout differs (shared clone; content unaffected)"
        print(f"[api/{name}] pin {pinned[:12]}, clone HEAD {head[:12]}: {same}")
        if tracked_dirty_status(repo):
            print("    WARNING: clone has tracked modifications")
    spec = spec_provenance(REPO_ROOT / hub["board_api"]["spec"])
    print(
        f"[api/board] spec blob {spec['sha'][:12]} "
        f"(last spec commit {spec['commit_date'][:10]})"
    )


def tracked_dirty_status(repo: Path) -> bool:
    return bool(sync_docs.tracked_dirty(repo))


