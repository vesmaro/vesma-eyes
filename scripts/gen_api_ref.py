def page_to_file(page: dict[str, Any], url_prefix: str) -> tuple[Path, str]:
    slug = f"{url_prefix}/{page['path'][: -len('.md')]}"
    fields = [
        ("title", str(page["title"])),
        ("slug", slug),
        ("category", str(page["category"])),
        ("order", str(int(page["order"]))),
        ("last_verified", str(page["provenance"]["commit_date"])[:10]),
    ] + list(page.get("extra_fields") or [])
    md = assemble_page(
        fields=fields,
        banner=page["banner"],
        note=page.get("note"),
        body=page["body"],
    )
    dest = CONTENT_UPSTREAM / url_prefix / page["locale"] / page["path"]
    return dest, md


def merge_manifests(
    pages: list[dict[str, Any]], url_prefix: str, hub: dict[str, Any], pins: dict[str, dict[str, Any]]
) -> dict[str, Any]:
    """Merge api pages into provenance.json + manifest.sidecar.json."""
    provenance_path = CONTENT_UPSTREAM / PROVENANCE_NAME
    sidecar_path = CONTENT_UPSTREAM / SIDECAR_NAME
    if not provenance_path.is_file() or not sidecar_path.is_file():
        raise SyncError(
            "api hub: provenance.json/manifest.sidecar.json missing — run "
            "sync_docs.py first (`npm run sync-docs` chains both)"
        )
    provenance = json.loads(provenance_path.read_text(encoding="utf-8"))
    sidecar = json.loads(sidecar_path.read_text(encoding="utf-8"))

    files = {
        slug: entry
        for slug, entry in provenance.get("files", {}).items()
        if not slug.startswith(f"{url_prefix}/")
    }
    sidecar_pages = {
        entry["slug"]: entry
        for entry in sidecar.get("pages", [])
        if not entry["slug"].startswith(f"{url_prefix}/")
    }

    by_slug: dict[str, dict[str, Any]] = {}
    for page in pages:
        slug = f"{url_prefix}/{page['path'][: -len('.md')]}"
        by_slug.setdefault(slug, {})[page["locale"]] = page

    for slug in sorted(by_slug):
        locales = by_slug[slug]
        first = locales[sorted(locales)[0]]
        titles = {loc: str(locales[loc]["title"]) for loc in sorted(locales)}
        files[slug] = {
            loc: {
                "repo": locales[loc]["provenance"]["repo"],
                "source_path": locales[loc]["provenance"]["source_path"],
                "sha": locales[loc]["provenance"]["sha"],
                "commit_date": locales[loc]["provenance"]["commit_date"],
                "synced_at": locales[loc]["provenance"]["commit_date"],
                "locale": loc,
                "kind": locales[loc]["kind"],
            }
            for loc in sorted(locales)
        }
        sidecar_pages[slug] = {
            "slug": slug,
            "titles": titles,
            "category": str(first["category"]),
            "order": int(first["order"]),
            "lastVerified": str(first["provenance"]["commit_date"])[:10],
            "locales": sorted(locales),
            "provenance": dict(first["provenance"]),
            "contentClass": {loc: "corpus" for loc in sorted(locales)},
        }

    projects = dict(provenance.get("projects") or {})
    projects["api_hub"] = {
        "board_api_spec": hub["board_api"]["spec"],
        "board_api_blob_sha": pins["__spec__"]["sha"],
        "sources": {
            name: {"repo": hub["sources"][name]["repo"], "ref": hub["sources"][name]["ref"], "sha": pins[name]["sha"]}
            for name in sorted(hub["sources"])
            if name in pins
        },
    }
    all_dates = [
        pin["commit_date"]
        for key, pin in pins.items()
        if key != "__spec__"
    ] + [pins["__spec__"]["commit_date"]]
    provenance_out = {
        "version": provenance.get("version", 1),
        "generated_by": "scripts/sync_docs.py + scripts/gen_api_ref.py",
        "synced_at": max(all_dates) if all_dates else None,
        "projects": projects,
        "files": dict(sorted(files.items())),
    }
    source_shas = dict(sidecar.get("source_shas") or {})
    source_shas.update(
        {
            f"api/{name}": pins[name]["sha"]
            for name in sorted(hub["sources"])
            if name in pins
        }
    )
    sidecar_out = {
        "version": sidecar.get("version", 1),
        "generated_by": "scripts/sync_docs.py + scripts/gen_api_ref.py",
        "source_shas": source_shas,
        "pages": [sidecar_pages[slug] for slug in sorted(sidecar_pages)],
    }
    provenance_path.write_text(
        json.dumps(provenance_out, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    sidecar_path.write_text(
        json.dumps(sidecar_out, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    return {"pages": len(by_slug), "files": len(files)}


# --------------------------------------------------------------------------
# sync
# --------------------------------------------------------------------------

def sync(config: dict[str, Any], hub: dict[str, Any]) -> dict[str, Any]:
    normalize = sync_docs.normalize_rules(config)
    pins: dict[str, dict[str, Any]] = {}
    for name, source in hub["sources"].items():
        pins[name] = pin_source(name, source)
    pins["__spec__"] = spec_provenance(REPO_ROOT / hub["board_api"]["spec"])

    sidecar_slugs: set[str] = set()
    sidecar_path = CONTENT_UPSTREAM / SIDECAR_NAME
    if sidecar_path.is_file():
        existing = json.loads(sidecar_path.read_text(encoding="utf-8"))
        sidecar_slugs = {entry["slug"] for entry in existing.get("pages", [])}

    report: dict[str, Any] = {"sources": {}, "skipped": [], "warnings": []}

    board_pages, total_ops = build_board_pages(hub["board_api"], pins["__spec__"])
    report["board_api"] = {
        "pages": len(board_pages),
        "operations": total_ops,
        "spec_blob": pins["__spec__"]["sha"][:12],
        "spec_version": json.loads((REPO_ROOT / hub["board_api"]["spec"]).read_text(encoding="utf-8"))["info"]["version"],
    }

    own_slugs = {
        f"{hub['url_prefix']}/{page['path'][: -len('.md')]}" for page in board_pages
    }
    corpus_slugs = sidecar_slugs | own_slugs

    pages = list(board_pages)
    for name, source in sorted(hub["sources"].items()):
        source_pages, source_report = build_source_pages(
            name, source, pins[name], corpus_slugs, normalize
        )
        pages.extend(source_pages)
        corpus_slugs |= {
            f"{hub['url_prefix']}/{page['path'][: -len('.md')]}" for page in source_pages
        }
        report["sources"][name] = {
            "sha": pins[name]["sha"],
            "pages": len(source_pages),
            **source_report,
        }

    curated_pages, warnings = build_curated_pages(hub["curated"], pins)
    pages.extend(curated_pages)
    report["warnings"].extend(warnings)

    # --- phase B: wipe the api subtree, write everything --------------------
    if API_DIR.exists():
        shutil.rmtree(API_DIR)
    for page in pages:
        dest, md = page_to_file(page, hub["url_prefix"])
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(md, encoding="utf-8")

    merged = merge_manifests(pages, hub["url_prefix"], hub, pins)

    # --- reuse the sync_docs contentClass gate over the FULL merged tree ----
    provenance = json.loads((CONTENT_UPSTREAM / PROVENANCE_NAME).read_text(encoding="utf-8"))
    sidecar = json.loads((CONTENT_UPSTREAM / SIDECAR_NAME).read_text(encoding="utf-8"))
    sidecar_by_slug = {entry["slug"]: entry for entry in sidecar["pages"]}
    sync_docs._verify_content_class_gate(sidecar_by_slug, provenance["files"], CONTENT_UPSTREAM)

    report.update(
        {
            "pages": merged["pages"],
            "provenance_files": merged["files"],
            "pins": {
                key: pin["sha"] if key != "__spec__" else pin["sha"]
                for key, pin in pins.items()
            },
        }
    )
    return report


