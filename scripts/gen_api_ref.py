def pin_source(name: str, source: dict[str, Any]) -> dict[str, Any]:
    """Resolve an api_hub source pin. Bodies are read from git OBJECTS of
    the pinned commit (`git show sha:path`), never from the clone's working
    tree — one clone may legitimately sit checked out at ANOTHER pin (the
    sync_docs projects share ../mnemos with a different ref), so the
    checkout state must not leak into api-hub content. No pristine check:
    dirty worktrees cannot affect object reads. ME-046: the pin must
    resolve (fetch-completeness) — an object the clone never fetched fails
    LOUD with a fetch hint, never falls through to empty output."""
    repo = (REPO_ROOT / source["repo"]).resolve()
    if not (repo / ".git").exists():
        raise SyncError(
            f"api_hub.sources.{name}: clone not found at {repo} — worktrees "
            f"need the wt/ mirror (see wt/README.md), the main checkout "
            f"resolves ../{name} directly"
        )
    sha = resolve_pin(repo, f"api_hub.sources.{name}", source["ref"])
    return {"repo_path": str(repo), "sha": sha, "commit_date": commit_iso(repo, sha)}


def spec_provenance(spec_path: Path) -> dict[str, Any]:
    """Content pin for the OpenAPI snapshot: git blob SHA + last commit date.

    A blob SHA survives our own commits unchanged — the pin follows the
    SPEC CONTENT, not the repo state (deterministic across re-runs).
    """
    if not spec_path.is_file():
        raise SyncError(f"api_hub.board_api: spec not found at {spec_path}")
    blob = hashlib.sha1(f"blob {spec_path.stat().st_size}\0".encode() + spec_path.read_bytes()).hexdigest()
    date = run_git(REPO_ROOT, "log", "-1", "--format=%cI", "--", str(spec_path.relative_to(REPO_ROOT)))
    if not date:
        date = run_git(REPO_ROOT, "log", "-1", "--format=%cI")
    return {"sha": blob, "commit_date": date}


