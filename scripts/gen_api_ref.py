"""API hub generator — /docs/api (owner directive 2026-09-29, board ME-038).

The api hub is the FOURTH docs hub and the first CROSS-CUTTING one: it
aggregates the API surfaces of the whole ecosystem under one URL prefix
(`api/…`). sync_docs.py cannot host it — one sync project is one repo — so
this generator owns the prefix end-to-end, in the same discipline as
sync_docs (ARCHCOM-7 contract §2 layers):

  L0  local clones pinned by full SHA in sync-config.yaml `api_hub.sources`
      (+ our own OpenAPI snapshot, pinned by its git blob SHA).
  L1  this script + the `api_hub:` section of scripts/sync-config.yaml
      (grouping map, selection, excludes with reasons on record).
  L2  generated corpus under viewer/src/features/docs/content/upstream/api/
      merged into provenance.json + manifest.sidecar.json.

Sections (categories.ts registry on the viewer side):
  api-overview        curated hub cover (what lives here, source map,
                      freshness rule);
  api-board           vesma-eyes board API — DETERMINISTIC rendering of
      viewer/board-openapi-snapshot.json (ru + en mirror, ME-044): path
      groups from the `board_api.groups` map, one page per group + an
      index page, built per locale (group title/about are locale mappings
      in the config; table chrome comes from RU_LABELS/EN_LABELS; the
      spec's own operation texts are EN in both locales). Hand retelling
      is FORBIDDEN: a spec change means regeneration. Provenance of every
      generated page = the spec's git blob SHA + the date of the last
      commit touching the spec (in frontmatter `source:` and in the
      sidecar provenance block) — identical for both locales.
  api-mnemos          vesma HTTP API surfaces: the upstream A2A Sessions
      API spec (docs/en|ru/architecture/a2a-sessions.md, previously outside
      every selection) + a curated map page over the full HTTP reference
      that already lives in the vesma hub (no duplicate corpus copies).
  api-agent           vesmaro-agent: the wire protocol body from the repo
      (docs/PROTOCOL.md, EN — shown under the original-language badge) + a
      curated digest of the service charter v2 with provenance.
  api-mesh            an HONEST short note: vesma-mesh has no public HTTP
      API — internal gRPC contracts only (verified against the mesh pin).

Curated bodies are authored OUTSIDE the wiped zone, in
viewer/src/features/docs/curated/api/<locale>/<path>.md (the same pattern
as sync_docs curated translations) and republished into the corpus on
every run — a missing curated file is a warning, the locale slot is
skipped.

Order of runs: `npm run sync-docs` chains sync_docs.py FIRST (it wipes
content/upstream/*, including api/) and THIS generator second. Running
gen_api_ref.py twice is byte-identical (no wall-clock anywhere), and
since ME-052 also ACROSS commits: every provenance anchor follows content
(the spec blob, upstream pins, the last change of a curated source), so
regenerating between unrelated main commits produces zero diff. Running
sync_docs.py alone leaves a consistent tree without api/ pages (the
sidecar is rebuilt from scratch there) — the npm chain is the contract.

Usage:
  python3 scripts/gen_api_ref.py sync            regenerate the api corpus
  python3 scripts/gen_api_ref.py                 (same, default command)
  python3 scripts/gen_api_ref.py check-drift     compare api_hub pins with
                                                 clone HEADs (report-only)

Exit codes: 0 ok, 1 error (bad pin, dirty clone, unmapped spec path,
config sanity, sidecar merge failure).
"""

